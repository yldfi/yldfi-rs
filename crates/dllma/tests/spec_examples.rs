//! Deserializes the example responses in DefiLlama's OpenAPI specs (free
//! and Pro), plus responses built from each endpoint's schema, into the type
//! this crate reads that endpoint's response as, so a type that no longer
//! matches the spec fails here instead of at runtime.
//!
//! Refresh the fixtures with `scripts/spec-check/examples.py`:
//! `python3 scripts/spec-check/examples.py
//! https://raw.githubusercontent.com/DefiLlama/api-docs/main/defillama-openapi-free.json
//! crates/dllma/tests/spec_examples/defillama.json` (and `-pro` into
//! `defillama-pro.json`).
#![allow(unused_imports)]

mod free {
    use dllma::{
        bridges, coins, dat, ecosystem, emissions, etf, fees, stablecoins, tvl, volumes, yields,
    };

    yldfi_spec_test::spec_tests! {
        file: "spec_examples/defillama.json",
        checks: {
            "GET /batchHistorical" => coins::BatchHistoricalResponse,
            "GET /block/{chain}/{timestamp}" => coins::BlockResponse,
            "GET /chart/{coins}" => coins::ChartResponse,
            "GET /chart/{pool}" => yields::YieldsResponse<Vec<yields::YieldChartPoint>>,
            "GET /overview/dexs" => volumes::VolumeOverview,
            "GET /overview/dexs/{chain}" => volumes::VolumeOverview,
            "GET /overview/fees" => fees::FeesOverview,
            "GET /overview/fees/{chain}" => fees::FeesOverview,
            "GET /overview/open-interest" => volumes::OpenInterestOverview,
            "GET /overview/options" => volumes::VolumeOverview,
            "GET /percentage/{coins}" => coins::PercentageResponse,
            "GET /pools" => yields::YieldsResponse<Vec<yields::YieldPool>>,
            "GET /prices/current/{coins}" => coins::PricesResponse,
            "GET /prices/first/{coins}" => coins::FirstPriceResponse,
            "GET /prices/historical/{timestamp}/{coins}" => coins::PricesResponse,
            "GET /protocol/{protocol}" => tvl::ProtocolDetail,
            "GET /protocols" => Vec<tvl::Protocol>,
            "GET /stablecoin/{asset}" => stablecoins::StablecoinDetail,
            "GET /stablecoinchains" => Vec<stablecoins::StablecoinChain>,
            "GET /stablecoincharts/all" => Vec<stablecoins::StablecoinChartPoint>,
            "GET /stablecoincharts/{chain}" => Vec<stablecoins::StablecoinChartPoint>,
            "GET /stablecoinprices" => stablecoins::StablecoinPricesResponse,
            "GET /stablecoins" => stablecoins::StablecoinsResponse,
            "GET /summary/dexs/{protocol}" => volumes::ProtocolVolumeSummary,
            "GET /summary/fees/{protocol}" => fees::ProtocolFeesSummary,
            "GET /tvl/{protocol}" => f64,
            "GET /v2/chains" => tvl::ChainsResponse,
            "GET /v2/historicalChainTvl" => tvl::ChainHistoricalTvl,
            "GET /v2/historicalChainTvl/{chain}" => tvl::ChainHistoricalTvl,
        },
        not_implemented: [
        ],
        skip: [
            (
                "GET /protocols",
                "sample",
                "the spec lists 9 protocol fields and omits slug, which live responses always send",
            ),
            (
                "GET /stablecoin/{asset}",
                "sample",
                "the spec documents chainCirculating as per-chain arrays, but live /stablecoin/{id} responses do not send chainCirculating",
            ),
        ],
    }
}

